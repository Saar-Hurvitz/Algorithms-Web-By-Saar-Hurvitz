// Writes docs/CONTENT_INVENTORY.md and reports entries with missing slides,
// bad slide references, missing slide images and uncovered checklist items.
global.window = global;
const fs = require('fs'), path = require('path');
const d = process.argv[2] ? path.resolve(process.argv[2]) : path.resolve(__dirname, '..');
global.E = {};
// The same week files, in the same order, as the page
const scripts = [...fs.readFileSync(d + '/index.html', 'utf8').matchAll(/<script src="(js\/[^"]+)"/g)].map(m => m[1]);
for (const f of scripts) if (/^js\/(course\.js|weeks\/)/.test(f)) require(d + '/' + f);

let n = 0, out = '# Content inventory\n\nGenerated by `tools/make-inventory.js`. Week 1 slides are L (lecture) and R (recitation). Later weeks start with the week number: 2L, 2R.\n';
const counts = {}, missing = [], slideErr = [], missingImg = [];
const parseRef = r => { const m = r.match(/^(\d*[A-Z])(\d+)$/); return m ? { info: COURSE.decks[m[1]], num: +m[2] } : {}; };
for (const w of COURSE.weeks) {
  out += `\n## Week ${w.n}: ${w.title}\n`;
  for (const p of COURSE.parts.filter(x => x.week === w.n)) {
    out += `\n### ${p.title}\n\n| # | Entry | Slides | Type | Checklist |\n|---|---|---|---|---|\n`;
    for (const e of p.entries) {
      n++;
      (e.checklist || []).forEach(c => { counts[c] = (counts[c] || 0) + 1; });
      if (!e.slides || !e.slides.length) missing.push(e.id);
      for (const r of e.slides || []) {
        const { info, num } = parseRef(r);
        if (!info || !(num >= 1 && num <= info.count)) { slideErr.push(e.id + ':' + r); continue; }
        const file = `${d}/${info.path}${String(num).padStart(String(info.count).length, '0')}.png`;
        if (!fs.existsSync(file)) missingImg.push(file);
      }
      const type = [e.algo && 'algorithm', e.exercise && 'exercise', e.recap && 'recap'].filter(Boolean).join(', ');
      out += `| ${n} | ${e.title} | ${(e.slides || []).join(' ')} | ${type} | ${(e.checklist || []).join(' ')} |\n`;
    }
  }
  out += `\n### Week ${w.n} checklist\n\n` + Object.entries(w.checklist).map(([k, t]) => `- **${k}** (${counts[k] || 0} entries): ${t}`).join('\n') + '\n';
  if (w.checklistNote) out += `\n${w.checklistNote}\n`;
}
fs.writeFileSync(d + '/docs/CONTENT_INVENTORY.md', out);
const uncovered = Object.keys(COURSE.checklist).filter(k => !counts[k]);
console.log('weeks', COURSE.weeks.length, 'entries', n, 'terms', Object.keys(COURSE.terms).length,
  '| no slides:', missing.length, 'bad refs:', slideErr.length, 'missing images:', missingImg.length, 'uncovered checklist items:', uncovered.length);
for (const [label, list] of [['no slides', missing], ['bad refs', slideErr], ['missing images', missingImg], ['uncovered', uncovered]]) if (list.length) console.log(' ', label + ':', list.join(' '));
process.exit(missing.length + slideErr.length + missingImg.length + uncovered.length ? 1 : 0);
